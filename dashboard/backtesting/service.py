def strategy_source(cls) -> Tuple[Optional[str], bool]:
    """(source text, custom): a custom class's file as executed, else its module's source."""
    text = cls.__dict__.get(STRATEGY_SOURCE_ATTR) if hasattr(cls, "__dict__") else None
