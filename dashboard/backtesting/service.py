class RunTask:
    """One run in the registry.

    Worker threads (the run, the reflection) change a task only under its lock
    (`update`, `set_reflection`, `report`), and readers copy it under the same lock
    (`snapshot`, `legacy_status`, `legacy_copy`). The dicts it holds (result, legacy,
    error, reflection) are never changed in place once set: a change replaces the
    dict, so what a reader holds stays consistent.
    """

    _FIELDS = frozenset({"status", "stage", "stage_detail", "progress", "started_at", "finished_at", "result",
                         "legacy", "error", "reflection", "saved"})

    def __init__(self, run_id: str, kind: str = "run"):
        self.lock = threading.RLock()
        self.id = run_id
        self.kind = kind                       # run / legacy / rerun / saved (loaded from history)
        self.status = "queued"                 # queued / running / completed / failed / cancelled
        self.stage: Optional[str] = None       # prepare_data / simulate / stats / done
        self.stage_detail: Optional[str] = None
        self.progress: Optional[float] = None
        self.created_at = datetime.now().isoformat(timespec="seconds")
        self.started_at: Optional[str] = None
        self.finished_at: Optional[str] = None
        self.result: Optional[Dict[str, Any]] = None
        self.legacy: Optional[Dict[str, Any]] = None
        self.error: Optional[Dict[str, Any]] = None
        self.reflection: Dict[str, Any] = {"status": "none", "result": None, "message": None}
        self.saved = False
        self.cancel_event = threading.Event()
        self.done_event = threading.Event()
        self.reflection_done = threading.Event()

    def update(self, **fields) -> None:
        unknown = set(fields) - self._FIELDS
        if unknown:
            raise AttributeError(f"RunTask has no field {', '.join(sorted(unknown))}")
        with self.lock:
            for key, value in fields.items():
                setattr(self, key, value)

    def set_reflection(self, state: Dict[str, Any], legacy: Optional[Dict[str, Any]] = None) -> None:
        """Replace the reflection state (and the legacy response's reflection keys)."""
        with self.lock:
            self.reflection = dict(state)
            if legacy and self.legacy is not None:
                self.legacy = {**self.legacy, **legacy}

    def legacy_copy(self) -> Optional[Dict[str, Any]]:
        with self.lock:
            return dict(self.legacy) if self.legacy is not None else None

    # Callbacks for the engine.
    def report(self, stage: str, detail: Any = None) -> None:
        with self.lock:
            if stage == "simulate" and isinstance(detail, (int, float)):
                self.stage, self.progress = "simulate", float(detail)
            elif stage in STAGE_LABELS:
                self.stage = stage
                self.stage_detail = STAGE_DETAILS.get(detail, detail) if isinstance(detail, str) else None
                self.progress = None

    def cancelled(self) -> bool:
        return self.cancel_event.is_set()

    @property
    def finished(self) -> bool:
        return self.status in ("completed", "failed", "cancelled")

    @property
    def reflecting(self) -> bool:
        return self.reflection.get("status") == "pending"

    def snapshot(self, with_result: bool = True) -> Dict[str, Any]:
        with self.lock:
            return self._snapshot(with_result)

    def _snapshot(self, with_result: bool) -> Dict[str, Any]:
        return {
            "run_id": self.id,
            "kind": self.kind,
            "status": self.status,
            "stage": self.stage,
            "stage_label": STAGE_LABELS.get(self.stage) if self.stage else None,
            "stage_detail": self.stage_detail,
            "progress": self.progress,
            "stages": [{"id": key, "label": label} for key, label in STAGES],
            "created_at": self.created_at,
            "started_at": self.started_at,
            "finished_at": self.finished_at,
            "error": self.error,
            "saved_to_history": self.saved,
            "reflection": dict(self.reflection),
            "result": self.result if with_result else None,
        }

    def legacy_status(self) -> Dict[str, Any]:
        with self.lock:
            return self._legacy_status()

    def _legacy_status(self) -> Dict[str, Any]:
        """The shape of the legacy GET /status/{run_id}."""
        status = {"queued": "running"}.get(self.status, self.status)
        if self.status == "completed":
            progress = "完成"
        elif self.error:
            progress = f"错误: {self.error['message']}"
        elif self.status == "cancelled":
            progress = "已取消"
        else:
            progress = STAGE_LABELS.get(self.stage, "排队中") if self.stage else "排队中"
        out = {"status": status, "progress": progress, "run_id": self.id, "has_result": self.legacy is not None}
        if self.error:
            out["message"] = self.error["message"]
        return out


class TaskRegistry:
    """In-process runs: at most `max_active` unfinished, at most `max_finished` kept after."""

    def __init__(self, max_finished: int = 50, max_active: int = 4):
        self.max_finished = max_finished
        self.max_active = max_active
        self._tasks: "OrderedDict[str, RunTask]" = OrderedDict()
        self._lock = threading.Lock()

    def __len__(self) -> int:
        return len(self._tasks)

    def __contains__(self, run_id) -> bool:
        return run_id in self._tasks

    def get(self, run_id: str) -> Optional[RunTask]:
        with self._lock:
            return self._tasks.get(run_id)

    def values(self) -> List[RunTask]:
        with self._lock:
            return list(self._tasks.values())

    def clear(self) -> None:
        with self._lock:
            for task in self._tasks.values():
                task.cancel_event.set()
            self._tasks.clear()

    def active(self) -> int:
        with self._lock:
            return self._active()

    def _active(self) -> int:
        return sum(1 for task in self._tasks.values() if not task.finished)

    def add(self, task: RunTask, *, limit: bool = True) -> RunTask:
        with self._lock:
            if limit and self._active() >= self.max_active:
                raise UserError(f"同时进行的回测已有 {self.max_active} 个，请等其中一个完成后再试", 429)
            self._tasks[task.id] = task
            self._evict()
        return task

    def add_if_absent(self, task: RunTask) -> RunTask:
        """The task registered under task.id, or `task` registered now (never replaces one)."""
        with self._lock:
            current = self._tasks.get(task.id)
            if current is not None:
                return current
            self._tasks[task.id] = task
            self._evict()
        return task

    def _evict(self) -> None:
        # A run whose reflection is still being written stays: its worker updates this
        # object, and a task rebuilt from history in its place would never see it.
        finished = [run_id for run_id, task in self._tasks.items() if task.finished and not task.reflecting]
        for run_id in finished[:max(0, len(finished) - self.max_finished)]:
            del self._tasks[run_id]

    def evict(self) -> None:
        with self._lock:
            self._evict()

    def cancel(self, run_id: str) -> Optional[RunTask]:
        task = self.get(run_id)
        if task is not None and not task.finished:
            task.cancel_event.set()
        return task


