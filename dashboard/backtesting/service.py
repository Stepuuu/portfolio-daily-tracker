# The packages whose code a strategy's signals depend on (indicator helpers, the
# strategy base class, the rule engine): fingerprinted per run (signal_dependencies).
SIGNAL_PACKAGES = ("backtesting.factors", "backtesting.strategies")


def _signal_module(name) -> bool:
    return isinstance(name, str) and any(name == package or name.startswith(package + ".")
                                         for package in SIGNAL_PACKAGES)


def _namespace_of(cls) -> Dict[str, Any]:
    """The globals of the module that defines `cls` (a custom file's namespace is not in
    sys.modules under a reliable name: a method's __globals__ is)."""
    for value in vars(cls).values():
        function = getattr(value, "__func__", value)
        namespace = getattr(function, "__globals__", None)
        if isinstance(function, types.FunctionType) and isinstance(namespace, dict):
            return namespace
    module = sys.modules.get(getattr(cls, "__module__", "") or "")
    return vars(module) if module is not None else {}


def _file_sha256(module) -> Optional[str]:
    try:
        with open(module.__file__, "rb") as handle:
            return hashlib.sha256(handle.read()).hexdigest()
    except (AttributeError, TypeError, OSError):
        return None


def signal_dependencies(cls) -> Dict[str, Optional[str]]:
    """{module name: sha256 of its source file (null: not readable)} for every module under
    SIGNAL_PACKAGES that the strategy's code reaches: the modules of its base classes,
    and every such module its own module's namespace holds (a module, or a class or
    function defined there), followed through those modules' namespaces in turn. A
    package is followed through what its __init__ binds other than submodules (which
    of those are attributes depends on what happened to be imported); a reference to
    the backtesting package itself counts as both packages. The class's own module is
    source_sha256, not listed here."""
    own = getattr(cls, "__module__", None)
    found: Dict[str, Optional[str]] = {}
    pending: List[Tuple[Dict[str, Any], bool]] = []

    def note(name) -> None:
        if not _signal_module(name) or name == own or name in found:
            return
        module = sys.modules.get(name)
        found[name] = _file_sha256(module) if module is not None else None
        if module is not None:
            pending.append((vars(module), hasattr(module, "__path__")))

    def scan(namespace: Dict[str, Any], package: bool = False) -> None:
        for value in list(namespace.values()):
            if isinstance(value, types.ModuleType):
                if package:
                    continue
                name = getattr(value, "__name__", None)
                if name == "backtesting":
                    for signal_package in SIGNAL_PACKAGES:
                        note(signal_package)
                note(name)
            elif isinstance(value, (type, types.FunctionType)):
                note(getattr(value, "__module__", None))

    for base in getattr(cls, "__mro__", ())[1:]:
        note(base.__module__)
    scan(_namespace_of(cls))
    while pending:
        scan(*pending.pop())
    return {name: found[name] for name in sorted(found)}


# Where the Python installation keeps its own modules: a module elsewhere (this project, or a
# file on the user's path) is code a custom strategy may import and change (local_dependencies).
_INSTALLED = ("site-packages", "dist-packages")


def _stdlib_dirs() -> List[Path]:
    import sysconfig
    found = []
    for key in ("stdlib", "platstdlib"):
        try:
            found.append(Path(sysconfig.get_paths()[key]).resolve())
        except (KeyError, OSError, RuntimeError, TypeError):
            continue
    return found


def _own_code_path(path) -> bool:
    """A source file outside the standard library and the installed packages."""
    try:
        path = Path(path).resolve()
    except (TypeError, OSError, RuntimeError):
        return False
    if set(_INSTALLED) & set(path.parts):
        return False
    for folder in _stdlib_dirs():
        try:
            path.relative_to(folder)
            return False
        except ValueError:
            continue
    return True


def _own_code_module(module) -> bool:
    """A module with a source file outside the standard library and the installed packages."""
    file = getattr(module, "__file__", None)
    return isinstance(file, str) and _own_code_path(file)


def _imports_of(source: str, package: Optional[str]) -> List[str]:
    """The modules a source text imports anywhere in it (also inside functions): `import a.b`
    gives a.b; `from a.b import c` gives a.b, and a.b.c when that is a module. A relative
    import is resolved against `package`; without one it stays its dotted text (no file can
    be told for it)."""
    import ast
    import importlib.util
    try:
        tree = ast.parse(source)
    except (SyntaxError, ValueError, TypeError):
        return []
    names: List[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names += [alias.name for alias in node.names]
        elif isinstance(node, ast.ImportFrom):
            base = node.module or ""
            if node.level:
                relative = "." * node.level + base
                try:
                    base = importlib.util.resolve_name(relative, package) if package else ""
                except (ImportError, ValueError):
                    base = ""
                if not base:
                    names.append(relative)
                    continue
            names.append(base)
            names += [f"{base}.{alias.name}" for alias in node.names
                      if alias.name != "*" and f"{base}.{alias.name}" in sys.modules]
    return names


def _unimported_file(name: str) -> Tuple[bool, Optional[str]]:
    """(found, source file) of a module that is not imported, without importing anything:
    (False, None) when it cannot be found (or its package is not imported either)."""
    import importlib.util
    parent = name.rpartition(".")[0]
    if parent and parent not in sys.modules:
        return False, None
    try:
        spec = importlib.util.find_spec(name)
    except Exception:
        return False, None
    if spec is None:
        return False, None
    return True, (spec.origin if spec.has_location else None)


def _hash_file(path: str) -> Optional[str]:
    try:
        with open(path, "rb") as handle:
            return hashlib.sha256(handle.read()).hexdigest()
    except (OSError, TypeError):
        return None


def local_dependencies(cls, exclude=()) -> Dict[str, Optional[str]]:
    """{module name: sha256 of its source file} of the modules outside SIGNAL_PACKAGES, the
    standard library and the installed packages (this project's own, or a file on the user's
    path) that a custom strategy's file reaches: a module (or a class or function
    defined in one) its namespace holds, followed through those modules' namespaces in turn
    (a package through what its __init__ binds other than submodules, as in
    signal_dependencies), and every module the file's own source imports anywhere, also by
    name (`from helper import ALLOCATION` leaves only the value in the namespace; such a
    module of SIGNAL_PACKAGES not in `exclude`, the dependencies, is listed here too). A module that cannot be resolved to a file (a relative import, a module that
    cannot be found) is listed with null: a rerun cannot verify it. A constant changed in a
    helper the file imports changes the strategy; the class's own module is source_sha256."""
    own = getattr(cls, "__module__", None)
    exclude = set(exclude or ())
    found: Dict[str, Optional[str]] = {}
    pending: List[Tuple[Dict[str, Any], bool]] = []

    def note(module, imported: bool = False) -> None:
        name = getattr(module, "__name__", None)
        if (not isinstance(name, str) or name == own or name in found or name == "backtesting"
                or (_signal_module(name) and (not imported or name in exclude)) or not _own_code_module(module)):
            return
        found[name] = _file_sha256(module)
        pending.append((vars(module), hasattr(module, "__path__")))

    def scan(namespace: Dict[str, Any], package: bool = False) -> None:
        for value in list(namespace.values()):
            if isinstance(value, types.ModuleType):
                if not package:
                    note(value)
            elif isinstance(value, (type, types.FunctionType)):
                module = sys.modules.get(getattr(value, "__module__", None) or "")
                if module is not None:
                    note(module)

    def imported(name: str) -> None:
        if name.startswith("."):
            found.setdefault(name, None)           # a relative import without a package
            return
        if name in found or name == own or name == "backtesting" or name in exclude:
            return
        module = sys.modules.get(name)
        if module is not None:
            note(module, imported=True)
            return
        located, path = _unimported_file(name)
        if not located:
            found[name] = None                     # imported where it never ran, and not to be found
        elif path is not None and _own_code_path(path):
            found[name] = _hash_file(path)

    scan(_namespace_of(cls))
    custom = cls.__dict__.get(STRATEGY_SOURCE_ATTR) if hasattr(cls, "__dict__") else None
    for name in _imports_of(custom, None) if isinstance(custom, str) else []:
        imported(name)
    while pending:
        scan(*pending.pop())
    return {name: found[name] for name in sorted(found)}


def compare_dependencies(saved, now: Dict[str, Optional[str]]) -> Tuple[List[str], List[str]]:
    """(changed, unknown) between a saved definition's dependencies and today's: the
    modules whose source differs (or that were added or removed), as Chinese fragments,
    and what could not be compared."""
    if not isinstance(saved, dict):
        return [], ["它依赖的指标和策略代码（backtesting/factors、backtesting/strategies 下的模块）"]
    changed, unknown = [], []
    for name in sorted(set(saved) | set(now)):
        path = name.replace(".", "/") + ".py"
        before, after = saved.get(name), now.get(name)
        if name not in saved:
            changed.append(f"新增 {path}")
        elif name not in now:
            changed.append(f"不再使用 {path}")
        elif before is None or after is None:
            unknown.append(path)
        elif before != after:
            changed.append(f"{path} {before[:8]} → {after[:8]}")
    return changed, unknown


def strategy_definition(cls, kwargs: Dict[str, Any], info: Dict[str, Any]) -> Dict[str, Any]:
    """What the strategy of a run is, for the manifest and for reruns.

    version          2 (1: without dependencies)
    kind, id         preset / strategy and its id
    class, module    the strategy class that ran
    kwargs           what engine.add_strategy received
    parameters       the strategy's parameters at the start of the run: the class
                     defaults overlaid with kwargs (what the strategy reads)
    resolved_params  the user-facing parameters after defaults (a preset's resolved
                     numbers; for a Python strategy the same as parameters)
    rule_spec        a preset run by RuleStrategy: the normalised rule spec it ran
    source           a custom strategy: the text of its file as executed (else null)
    source_sha256    sha256 of the UTF-8 source of the class's module (a custom file,
                     a built-in strategy, or strategies/rules.py for a preset); null
                     when the source cannot be read
    sha256           sha256 of canonical_json({class, parameters, source_sha256})
                     (sorted keys, no spaces, UTF-8)
    dependencies     {module: sha256 of its source file} of the modules under
                     backtesting/factors and backtesting/strategies the strategy's code
                     reaches (signal_dependencies), e.g. the RSI and SMA helpers a rule
                     reads; a rerun compares them (strategy_changed, or
                     strategy_unverified when the saved record has none)
    dependencies_sha256  sha256 of canonical_json(dependencies)
    local_modules    a custom strategy: {module: sha256 of its source file} of the modules
                     outside those packages, the standard library and the installed packages
                     (the project's own, a file on the user's path) that its file reaches
                     or imports, also by name (local_dependencies); null for a module that
                     cannot be resolved to a file. Compared by a rerun like dependencies (a
                     record saved without them, or a null, is strategy_unverified); null
                     for other strategies
    """
    source, custom = strategy_source(cls)
    parameters = _jsonable({**(getattr(cls, "parameters", None) or {}), **kwargs})
    rule = kwargs.get("spec") if cls.__name__ == "RuleStrategy" and isinstance(kwargs.get("spec"), dict) else None
    if info.get("kind") == "preset" and rule is not None and isinstance(rule.get("params"), dict):
        resolved = rule["params"]
    else:
        resolved = parameters
    source_sha = hashlib.sha256(source.encode("utf-8")).hexdigest() if source is not None else None
    core = {"class": cls.__name__, "parameters": parameters, "source_sha256": source_sha}
    dependencies = signal_dependencies(cls)
    return _jsonable({
        "version": 2, "kind": info.get("kind"), "id": info.get("id"), "class": cls.__name__,
        "module": getattr(cls, "__module__", None), "kwargs": kwargs, "parameters": parameters,
        "resolved_params": resolved, "rule_spec": rule, "source": source if custom else None,
        "source_sha256": source_sha, "sha256": hashlib.sha256(canonical_json(core).encode("utf-8")).hexdigest(),
        "dependencies": dependencies,
        "dependencies_sha256": hashlib.sha256(canonical_json(dependencies).encode("utf-8")).hexdigest(),
        "local_modules": local_dependencies(cls, exclude=dependencies) if custom else None,
    })


def check_strategy_params(cls, params: Dict[str, Any], *, strict: bool) -> Dict[str, Any]:
    """Params for a Python strategy: numeric defaults need finite numbers; unknown keys
    are refused when strict (the new routes) and passed through for legacy callers."""
    defaults = dict(getattr(cls, "parameters", None) or {})
    out = {}
    for key, value in params.items():
        if key not in defaults:
            if strict:
                known = "、".join(defaults) or "无"
                raise UserError(f"策略 {cls.__name__} 没有参数 {key}；可用参数：{known}")
            out[key] = value
            continue
        default = defaults[key]
        if isinstance(default, (int, float)) and not isinstance(default, bool):
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(float(value)):
                raise UserError(f"参数 {key} 必须是有限的数字，收到 {value!r}")
            if isinstance(default, int) and float(value).is_integer():
                value = int(value)
        elif isinstance(default, bool) and not isinstance(value, bool):
            raise UserError(f"参数 {key} 必须是 true 或 false，收到 {value!r}")
        out[key] = value
    return out


def translate_legacy_fees(commission_sell, basis, market: str, ticker: str):
    """(components the sell rate includes, record or None) for the legacy routes.

    basis "commission_only": the fields are the broker commission; nothing changes.
    basis "legacy_inclusive" or missing (every client before fee_basis existed): the
    v3.2 meaning. v3.2 charged a sale exactly commission_sell (at least min_commission)
    and nothing else: the rate folded in the stamp duty of its time (the old page's
    default 0.0013 = commission 0.0003 + stamp duty 0.001, labelled 含印花税). Such a
    sale is charged the same here: the sent rate as the commission and no stamp duty on
    top of it (the sell rate includes ["stamp_duty"], see InclusiveSellConfig); the fees
    v3.2 did not know, which the dated schedule lists separately (A-share transfer fee,
    HK trading fee and levies, US SEC fee), are added at the rates of the trade date.
    Buys are unchanged: commission_buy was the commission only, and the dated taxes and
    levies of a buy are charged as for any request.
    Nothing changes, and nothing is recorded, when commission_sell is not sent (the
    market default is a commission only) or the market charges no stamp duty on this
    instrument's sales (the rate means the same either way). The record (basis, the sent
    and the used sell rate, what the rate includes and what is still charged on top)
    goes into the manifest and the legacy_fees_translated caveat.
    """
    if basis == "commission_only" or commission_sell is None:
        return [], None
    schedule = default_schedule()
    kind = market_rules.instrument_kind(ticker, market)
    sold = {name: spec for name, spec in schedule.components(market).items()
            if "sell" in spec["sides"] and kind in spec["applies_to"]}
    if "stamp_duty" not in sold:
        return [], None
    included = ["stamp_duty"]
    return included, {"basis": "legacy_inclusive", "commission_sell_sent": commission_sell,
                      "commission_sell_used": commission_sell, "included_in_sell_rate": included,
                      "charged_on_top": [name for name in sold if name not in included]}


@dataclass
class InclusiveSellConfig(BrokerConfig):
    """BrokerConfig whose sell commission rate already includes some dated components.

    A legacy request's commission_sell includes the stamp duty (translate_legacy_fees):
    a sale is charged that rate as the commission and the components named in
    sell_rate_includes are not charged again; every other component of the schedule
    is. Buys are charged as by BrokerConfig."""
    sell_rate_includes: Tuple[str, ...] = ()

    def fees_for(self, symbol: str, side: str, quantity, price, when):
        fees = super().fees_for(symbol, side, quantity, price, when)
        if side != "sell" or not self.sell_rate_includes:
            return fees
        dropped = Decimal(0)
        for name in self.sell_rate_includes:
            amount = getattr(fees, name, 0.0) or 0.0
            if amount:
                dropped += Decimal(str(amount))
                setattr(fees, name, 0.0)
            if name in fees.assumed_components:
                fees.assumed_components.remove(name)
        fees.assumed = bool(fees.assumed_components)
        fees.total = float(Decimal(str(fees.total)) - dropped)
        return fees


def check_broker(broker: Dict[str, Any]) -> None:
    def number(value):
        return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(float(value))

    for key, label in (("commission_buy", "买入佣金率"), ("commission_sell", "卖出佣金率")):
        value = broker.get(key)
        if value is not None and not (number(value) and 0 <= value < 1):
            raise UserError(f"{label}必须是 0 到 1 之间的小数（0.0003 表示 0.03%），收到 {value!r}")
    minimum = broker.get("min_commission")
    if minimum is not None and not (number(minimum) and minimum >= 0):
        raise UserError(f"最低佣金不能为负数，收到 {minimum!r}")
    slippage = broker.get("slippage_pct")
    if not (number(slippage) and 0 <= slippage < 1):
        raise UserError(f"滑点必须是 0 到 1 之间的小数（0.0005 表示 0.05%），收到 {slippage!r}")
    try:
        make_broker_config(broker)
    except ValueError:
        raise UserError("交易成本设置不正确") from None


def make_broker_config(broker: Dict[str, Any]) -> BrokerConfig:
    settings = dict(
        commission_buy=broker.get("commission_buy"), commission_sell=broker.get("commission_sell"),
        min_commission=broker.get("min_commission"), slippage_pct=broker.get("slippage_pct", DEFAULT_SLIPPAGE),
        lot_size=broker.get("lot_size"), market=broker.get("market", "auto"),
    )
    included = broker.get("sell_rate_includes")
    if included:
        return InclusiveSellConfig(**settings, sell_rate_includes=tuple(included))
    return BrokerConfig(**settings)


# How manifest.data_sha256 is made. 1: bars_sha256 rule 1 (OHLCV and amount only).
# 2: bars_sha256 rule 2 (every bar column). 3: rule 2 plus, per coverage, features_sha256:
# bars_sha256 of the frame handed to the strategy (the bars and the engine's derived
# features, warm-up included). A rerun compares data only under the same rule.
DATA_HASH_VERSION = 3


def combined_sha256(coverage: List[Dict[str, Any]]) -> str:
    """sha256 of the lines "<ticker>|<adjust>|<sha256>|<features_sha256 or empty>\n" of
    every coverage, sorted by ticker and adjust (DATA_HASH_VERSION 3)."""
    digest = hashlib.sha256()
    for item in sorted(coverage, key=lambda c: (c.get("ticker", ""), c.get("adjust", ""))):
        digest.update(f"{item.get('ticker')}|{item.get('adjust')}|{item.get('sha256')}|"
                      f"{item.get('features_sha256') or ''}\n".encode())
    return digest.hexdigest()


@functools.lru_cache(maxsize=1)
def _holiday_table() -> Dict[str, Dict[int, frozenset]]:
    try:
        from core.market.calendar import load_holidays
        return load_holidays()
    except Exception:                      # no table: no closure can be confirmed
        logger.exception("[Backtest] the holiday table could not be read")
        return {}


def index_market_closed(day, index_market: str) -> Optional[bool]:
    """Whether the index's exchange was closed on `day`: True on a weekend or a day the
    shipped holiday table (core/market/holidays.json) lists for that market and year,
    False on a weekday the table covers and does not list, None when the table has no
    data for that year (unknown, never assumed either way)."""
    moment = pd.Timestamp(day)
    if moment.weekday() >= 5:
        return True
    listed = _holiday_table().get(index_market, {}).get(moment.year)
    if listed is None:
        return None
    return moment.date() in listed


def index_session_gaps(equity_days: List[str], index_days: List[str], *, same_calendar: bool,
                       index_market: str) -> Tuple[List[str], List[str], List[str]]:
    """(gaps, closed, contradicted) for comparing a run with an index.

    gaps: the run's trading days without an index bar that the index cannot stand in
    for; closed: those it can (its exchange was closed; it keeps its last close);
    contradicted: index sessions inside the run that are absent from the run's calendar
    and fall on a day the index's own exchange was closed (a weekend, or a closure the
    holiday table lists), so its data cannot be trusted for the comparison. The
    comparison needs gaps and contradicted to be empty.

    The rule:
      * The index needs a bar on or before the first trading day (the base); without
        one every day is a gap.
      * Same exchange calendar (the index of the stock's own market): every trading day
        of the stock is a session of the index's exchange, so every missing bar is a
        gap. No forward fill.
      * Another market's index has its own holidays. A missing day is a closure only
        when index_market_closed says so (a weekend, or a closure the shipped holiday
        table lists for that market and year). Where the table has no data for the
        year nothing explains the missing bar: it is a gap, never an assumed holiday.
      * Index sessions between the first and the last trading day that are absent from
        the run's calendar (the index's market traded while the stock's was closed, or
        the stock had no bar) never enter the curve directly, but they are checked
        against the same calendar: a bar on a day the index's exchange was closed
        contradicts it.
    """
    if not equity_days:
        return [], [], []
    have = sorted(set(index_days))
    present = set(have)
    stamps = [pd.Timestamp(day) for day in have]
    first, last = pd.Timestamp(equity_days[0]), pd.Timestamp(equity_days[-1])
    if not stamps or stamps[0] > first:
        return [day for day in equity_days if day not in present] or list(equity_days[:1]), [], []
    gaps, closed = [], []
    for day in equity_days:
        if day in present:
            continue
        if same_calendar or index_market_closed(day, index_market) is not True:
            gaps.append(day)
        else:
            closed.append(day)
    run_days = set(equity_days)
    contradicted = [day for day, stamp in zip(have, stamps)
                    if first <= stamp <= last and day not in run_days
                    and index_market_closed(stamp, index_market) is True]
    return gaps, closed, contradicted


def equity_rows(result) -> List[Dict[str, Any]]:
    df = result.equity_df
    if df.empty:
        return []
    df = df[~df.index.duplicated(keep="last")]
    return [{"date": day.strftime("%Y-%m-%d"), "total_value": round(float(row["total_value"]), 2),
             "cash": round(float(row["cash"]), 2), "market_value": round(float(row["market_value"]), 2),
             "net_value": round(float(row["net_value"]), 6), "drawdown": round(float(row["drawdown"]), 6)}
            for day, row in df.iterrows()]


def drawdown_dates(equity: List[Dict[str, Any]]) -> Tuple[Optional[str], Optional[str]]:
    if not equity:
        return None, None
    values = pd.Series([row["total_value"] for row in equity], index=[row["date"] for row in equity])
    drawdown = values / values.cummax() - 1
    if float(drawdown.min()) >= 0:
        return None, None
    trough = drawdown.idxmin()
    peak = values.loc[:trough].idxmax()
    return peak, trough


# The buy_and_hold preset's rule (presets.py): buy with all the capital on the first
# tradable bar (whole lots, fees included, at the next open), hold to the end.
SAME_STOCK_SPEC = {"entry": {"rule": "always"}, "exits": [], "position_pct": 100, "name": "一直持有"}


def same_stock_benchmark(engine: BacktestEngine, plan: "Plan", bars: Optional[pd.DataFrame] = None) -> Dict[str, Any]:
    """Holding the same stock, simulated like the run itself.

    The same bars (warm-up included: `bars`, the frame handed to the strategy as the
    engine froze it before the run (BacktestEngine.loaded_frame), so nothing the
    strategy did to its frame reaches it), capital,
    broker settings (commission, minimum,
    taxes by date, slippage, lot rules, T+1, price limits, volume cap) and next-open
    execution as the run, with the buy_and_hold rule (SAME_STOCK_SPEC). Its
    total_return is the final value against the capital, after every fee; the
    position still held at the end is valued at the last close like the run's.
    When it never buys (one lot costs more than the capital, or the stock could not
    be bought), total_return is None and `reason` says why; never 0.

    {ticker, total_return, curve: [{date, value}], basis: "executable", fills,
     fees_total, entry: {date, price, quantity} | None, reason}
    """
    from backtesting.strategies.rules import RuleStrategy
    part = {"ticker": plan.symbol.ticker, "total_return": None, "curve": [], "basis": "executable",
            "fills": 0, "fees_total": 0.0, "entry": None, "reason": None}
    feed = engine._data_feeds.get(plan.label)
    frame = bars if bars is not None else (engine.loaded_frame(plan.label) if feed is not None else None)
    if feed is None or frame is None or len(frame) <= feed.warmup:
        part["reason"] = "这段区间没有可以交易的日子，算不出“一直持有”的对照收益。"
        return part
    # Everything about the comparison, its lazily computed statistics included, stays
    # inside this boundary: it can only make the comparison unavailable, never change or
    # abort the run's own result.
    try:
        hold = BacktestEngine(initial_cash=plan.capital, broker_config=make_broker_config(plan.broker),
                              use_cache=False, loader=object(), run_id=f"{plan.run_id}-hold")
        hold.add_data(plan.label, plan.start, plan.end, adjust=plan.adjust, df=frame.copy(deep=True),
                      warmup=plan.warmup, ticker=plan.symbol)
        hold.add_strategy(RuleStrategy, spec=dict(SAME_STOCK_SPEC))
        held = hold.run()
        buys = [trade for trade in held.trades if trade.direction == "buy"]
        if not buys:
            reasons = [UNFILLED_REASON_ZH.get(entry.get("reason"), entry.get("reason")) for entry in held.unfilled
                       if entry.get("direction") == "buy"]
            why = f"（{reasons[0]}）" if reasons else ""
            unit = summary.CURRENCY_UNITS.get(plan.symbol.currency, plan.symbol.currency)
            part["reason"] = (f"按同样的本金 {plan.capital:,.2f} {unit}、每手股数和费用，一直持有 {plan.symbol.ticker} "
                              f"也买不进{why}，没有“一直持有”的对照收益；这一栏是不可用，不是 0。")
            return part
        rows = equity_rows(held)
        first = buys[0]
        total = float(held.stats.total_return)
        if not math.isfinite(total):
            raise ArithmeticError("the comparison's total return is not finite")
        found = {
            "total_return": round(total, 6),
            "curve": [{"date": row["date"], "value": round(row["total_value"] / plan.capital, 6)} for row in rows],
            "fills": len(held.trades), "fees_total": round(float(held.fees_total), 2),
            "entry": {"date": pd.Timestamp(first.timestamp).strftime("%Y-%m-%d"),
                      "price": round(float(first.price), 4), "quantity": first.quantity},
        }
    except Exception:                   # the comparison must never fail the run itself
        logger.exception("[Backtest] the same-stock comparison of run %s failed", plan.run_id)
        part["reason"] = "“一直持有”的对照没有算出来（内部错误，详情见服务端日志）；这一栏是不可用，不是 0。"
        return part
    part.update(found)
    return part


def with_executable_benchmark(metrics: Dict[str, Any], same_part: Dict[str, Any]) -> Dict[str, Any]:
    """metrics with benchmark_return and alpha from the executable same-stock run
    (the engine's own are closes divided by the first close, without costs)."""
    out = dict(metrics)
    undefined = dict(out.get("undefined") or {})
    same = same_part.get("total_return")
    if same is None:
        out["benchmark_return"] = out["alpha"] = None
        reason = same_part.get("reason") or "没有“一直持有”的对照收益"
        undefined["benchmark_return"] = undefined["alpha"] = reason
    else:
        out["benchmark_return"] = round(same, 6)
        total = out.get("total_return")
        out["alpha"] = round(total - same, 6) if isinstance(total, (int, float)) else None
        undefined.pop("benchmark_return", None)
        undefined.pop("alpha", None)
    out["undefined"] = undefined
    return out


def end_mark_positions(result) -> Dict[str, Dict[str, Any]]:
    """{symbol: the engine's end_mark position with blocked_zh}: why the end-of-data
    valuation could not really be a sale (summary.end_mark_blocked_text), or None."""
    out = {}
    for mark in (result.end_mark or {}).get("positions") or []:
        blocked = mark.get("blocked")
        out[mark.get("symbol")] = {**mark, "blocked": blocked, "blocked_quantity": mark.get("blocked_quantity") or 0,
                                   "blocked_zh": summary.end_mark_blocked_text(blocked, mark.get("quantity"),
                                                                               mark.get("blocked_quantity"))}
    return out


def end_mark_fields(trade_reason, symbol, marks: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    """end_mark, blocked, blocked_quantity, blocked_zh of one fill or round trip."""
    if trade_reason != "end_mark":
        return {"end_mark": False, "blocked": None, "blocked_quantity": 0, "blocked_zh": None}
    mark = marks.get(symbol) or {}
    return {"end_mark": True, "blocked": mark.get("blocked"), "blocked_quantity": mark.get("blocked_quantity") or 0,
            "blocked_zh": mark.get("blocked_zh")}


def with_end_mark(trip: Dict[str, Any], marks: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    fields = end_mark_fields("end_mark" if trip.get("end_mark") else None, trip.get("symbol"), marks)
    return {**trip, **{key: value for key, value in fields.items() if key != "end_mark"}}


def fill_rows(result, marks: Optional[Dict[str, Dict[str, Any]]] = None) -> List[Dict[str, Any]]:
    """Every fill. The end-of-data valuation is reason "end_mark" with end_mark true and,
    when it could not really be sold, blocked (suspended / limit_down / t_plus_one),
    blocked_quantity and the Chinese blocked_zh."""
    marks = end_mark_positions(result) if marks is None else marks
    return [{
        "date": pd.Timestamp(trade.timestamp).strftime("%Y-%m-%d"),
        "symbol": trade.symbol, "direction": trade.direction, "quantity": trade.quantity,
        "price": round(float(trade.price), 4), "commission": round(float(trade.commission), 2),
        "fees": dict(trade.fees or {}), "pnl": round(float(trade.pnl), 2),
        "reason": trade.reason, "reason_zh": summary.EXIT_REASON_ZH.get(trade.reason, trade.reason)
        if trade.direction == "sell" else None,
        **end_mark_fields(trade.reason, trade.symbol, marks),
    } for trade in result.trades]


def monthly_returns(equity: List[Dict[str, Any]], capital: float) -> List[Dict[str, Any]]:
    if not equity:
        return []
    values = pd.Series([row["total_value"] for row in equity],
                       index=pd.DatetimeIndex([row["date"] for row in equity]))
    month_end = values.groupby([values.index.year, values.index.month]).last()
    out, previous = [], float(capital)
    for (year, month), value in month_end.items():
        out.append({"year": int(year), "month": int(month), "return": round(float(value) / previous - 1, 6)})
        previous = float(value)
    return out


