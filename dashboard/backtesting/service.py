def dated_rate_text(schedule, market: str, component: str, start=None, end=None) -> str:
    """The rate of one dated component over [start, end] as the run was charged it:
    "0.002%", or "0.002%（2022-04-29 起 0.001%）" when it changed inside the window.
    Without a window, the rate in force today."""
    def day(value):
        return value if isinstance(value, date) or value is None else date.fromisoformat(str(value)[:10])

    first, last = day(start), day(end)
    if first is None:
        first = last = date.today()
    rate, _ = schedule.rate(market, component, first)
    changes = sorted((date.fromisoformat(row["from"]), row["rate"])
                     for row in schedule.components(market)[component]["rows"])
    later = [f"{when.isoformat()} 起 {float(value) * 100:.3g}%" for when, value in changes
             if first < when <= (last or first)]
    return f"{float(rate) * 100:.3g}%" + (f"（{'、'.join(later)}）" if later else "")


def assumptions_line(plan, start=None, end=None) -> str:
    """One Chinese line of the run's assumptions (fees, slippage, execution, prices, benchmark).

    start, end: the dates the run traded on (YYYY-MM-DD or date). The rates of the
    dated components are those of these dates (dated_rate_text), not today's."""
    market = plan.market_code
    schedule = default_schedule()
    label = summary.MARKET_LABELS[plan.symbol.market]
    unit = summary.CURRENCY_UNITS.get(plan.symbol.currency, plan.symbol.currency)
    broker = plan.broker
    rate_default, min_default = schedule.commission_default(market)
    buy = broker.get("commission_buy")
    sell = broker.get("commission_sell")
    minimum = broker.get("min_commission")
    rate = float(rate_default) if buy is None and sell is None else None
    if rate is not None:
        commission = "佣金 0" if rate == 0 and (minimum or float(min_default)) == 0 else \
            f"佣金 {rate * 100:.3g}% 最低 {float(minimum if minimum is not None else min_default):g} {unit}"
    else:
        sides = {f"{(buy if buy is not None else float(rate_default)) * 100:.3g}%",
                 f"{(sell if sell is not None else float(rate_default)) * 100:.3g}%"}
        commission = f"佣金 {'/'.join(sorted(sides))} 最低 {float(minimum if minimum is not None else min_default):g} {unit}"
    kind = market_rules.instrument_kind(plan.symbol.ticker, market)
    included = set(broker.get("sell_rate_includes") or [])
    taxes = []
    for component, spec in schedule.components(market).items():
        if kind not in spec["applies_to"]:
            continue
        name = FEE_COMPONENT_NAMES.get(component, component)
        side = SIDE_NAMES.get(tuple(spec["sides"]), "")
        if component == "sec_fee":
            taxes.append(f"{side} SEC 费按当时费率")
        elif component == "stamp_duty" and component in included:
            # A legacy request's sell rate already holds it (translate_legacy_fees).
            taxes.append(f"卖出{name}含在卖出佣金里" if side != "双边" else f"买入{name}按当时税率，卖出{name}含在卖出佣金里")
        elif component == "stamp_duty":
            taxes.append(f"{side}{name}按当时税率" if side != "双边" else f"{name}按当时税率（双边）")
        else:
            taxes.append(f"{name} {dated_rate_text(schedule, market, component, start, end)}")
    fees = f"{label}费率（{'，'.join([commission] + taxes)}）"
    slippage = float(broker.get("slippage_pct") if broker.get("slippage_pct") is not None else DEFAULT_SLIPPAGE)
    benchmark = getattr(plan, "benchmark", None)
    compare = f"对比{INDEX_NAMES.get(benchmark, benchmark)}" if benchmark else "不对比指数"
    adjust = summary.ADJUST_LABELS.get(getattr(plan, "adjust", "qfq"), "前复权")
    return f"{fees}，滑点 {slippage * 100:.3g}%，次日开盘成交，{adjust}，{compare}"


def legacy_response(plan: Plan, result, run_result: Dict[str, Any]) -> Dict[str, Any]:
    """The legacy /run-sync body: the old keys unchanged, new keys added."""
    data = result.to_dict()
    data["summary"] = result.summary()
    data["start_date"] = plan.start
    data["end_date"] = plan.end
    data["strategy_class"] = plan.strategy_cls.__name__
    data["equity_curve"] = [{"date": row["date"], "net_value": round(row["net_value"], 4),
                             "drawdown": round(row["drawdown"], 4)} for row in run_result["equity"]]
    # The old trade table showed the end-of-data valuation as an ordinary sale: each row now
    # says what it is (reason, reason_zh, end_mark) and why it could not really be sold.
    marks = end_mark_positions(result)

    def reason_zh(trade, fields):
        if fields["end_mark"]:
            return summary.END_MARK_ZH + (f"：{fields['blocked_zh']}" if fields["blocked_zh"] else "")
        return summary.EXIT_REASON_ZH.get(trade.reason, trade.reason) if trade.direction == "sell" else None

    data["trade_records"] = []
    for t in result.trades:
        fields = end_mark_fields(t.reason, t.symbol, marks)
        data["trade_records"].append({
            "date": str(t.timestamp), "symbol": t.symbol, "direction": t.direction, "quantity": t.quantity,
            "price": round(t.price, 2), "pnl": round(t.pnl, 2), "commission": round(t.commission, 2),
            "reason": t.reason, "reason_zh": reason_zh(t, fields), **fields,
        })
    if data.get("end_mark"):
        data["end_mark"] = {**data["end_mark"], "positions": list(marks.values())}
    # The comparison with holding the stock is the executable one (same capital, fees,
    # slippage, lots, next-open fills), as in the RunResult; so is the summary text.
    metrics = run_result["metrics"]
    data["benchmark_return"], data["alpha"] = metrics.get("benchmark_return"), metrics.get("alpha")
    data["summary"] = _summary_with_benchmark(data["summary"], data["benchmark_return"], data["alpha"])
    data["reflection"] = None
    data["reflection_status"] = "none"
    # Additive fields.
    data["caveats"] = run_result["caveats"]
    data["ticker"] = plan.symbol.ticker
    data["headline_zh"] = run_result["headline_zh"]
    data["benchmark"] = run_result["benchmark"]
    data["manifest"] = run_result["manifest"]
    return _jsonable(data)


def same_hash_rule(original_manifest: Dict[str, Any], manifest: Dict[str, Any]) -> bool:
    """True when both manifests hashed their data by the same rule (DATA_HASH_VERSION);
    a record saved before data_hash_version existed used rule 1."""
    return (original_manifest or {}).get("data_hash_version", 1) == manifest.get("data_hash_version", 1)


def _summary_with_benchmark(text: str, benchmark, alpha) -> str:
    def line(label, value, note=""):
        shown = f"{value:>14.2%}" if isinstance(value, (int, float)) else f"{'不可用':>12}"
        return f"{label}: {shown}{note}"

    out = []
    for row in str(text).split("\n"):
        if row.startswith("基准收益:"):
            row = line("基准收益", benchmark, "  (同样本金和费用一直持有)")
        elif row.startswith("超额收益:"):
            row = line("超额收益", alpha)
        out.append(row)
    return "\n".join(out)


def rerun_caveats(original: Dict[str, Any], manifest: Dict[str, Any]) -> List[Dict[str, str]]:
    before_manifest = original.get("manifest") or {}
    if not same_hash_rule(before_manifest, manifest):
        out = [summary.data_unverified_caveat(before_manifest.get("data_hash_version", 1),
                                              manifest.get("data_hash_version"))]
    else:
        def hashes(item):
            return item.get("sha256"), item.get("features_sha256")

        before = {c.get("ticker"): hashes(c) for c in before_manifest.get("coverage") or []}
        after = {c.get("ticker"): hashes(c) for c in manifest.get("coverage") or []}
        changes = []
        for ticker in sorted(set(before) | set(after)):
            old, new = before.get(ticker), after.get(ticker)
            if old == new:
                continue
            if old is not None and new is not None and old[0] == new[0]:
                # The same bars; the features computed from them differ (their code changed).
                changes.append({"ticker": ticker, "before": old[1], "after": new[1], "features": True})
            else:
                changes.append({"ticker": ticker, "before": old and old[0], "after": new and new[0]})
        out = [summary.data_changed_caveat(changes)] if changes else []
    old_version = (original.get("manifest") or {}).get("engine_version")
    if old_version != manifest.get("engine_version"):
        out.append(summary.engine_changed_caveat(old_version, manifest.get("engine_version")))
    return out


def rerun_summary(original: Dict[str, Any], manifest: Dict[str, Any], metrics: Dict[str, Any]) -> Dict[str, Any]:
    before_manifest = original.get("manifest") or {}
    old_metrics = original.get("metrics") or {}
    changed = {key: [old_metrics.get(key), value] for key, value in metrics.items()
               if key in old_metrics and old_metrics.get(key) != value}
    return {
        "of": original.get("run_id"),
        "data_sha256_before": before_manifest.get("data_sha256"),
        "data_sha256_after": manifest.get("data_sha256"),
        # None: the saved hash was made by another rule and cannot be compared.
        "same_data": (before_manifest.get("data_sha256") == manifest.get("data_sha256"))
        if same_hash_rule(before_manifest, manifest) else None,
        "data_hash_version_before": before_manifest.get("data_hash_version", 1),
        "engine_version_before": before_manifest.get("engine_version"),
        "metrics_identical": bool(old_metrics) and not changed,
        "changed_metrics": changed,
    }
