def settings_caveats(before: Optional[Dict[str, Any]], after: Dict[str, Any], *,
                     before_manifest: Optional[Dict[str, Any]] = None, unverified=()) -> List[Dict[str, str]]:
    """Caveats for a rerun whose resolved settings differ from the saved run's.

    A record saved before manifest.resolved existed has nothing to compare: the fee
    table is compared by its version when the manifest has one (settings_changed), and
    everything else is named in a settings_unverified caveat, never assumed the same.
    `unverified`: more settings planning could not check (e.g. what "auto" meant)."""
    out = []
    if not isinstance(before, dict):
        old_version = (before_manifest or {}).get("fee_schedule_version")
        if old_version and old_version != after.get("fee_schedule_version"):
            out.append(summary.settings_changed_caveat([SETTING_LABELS["fee_schedule_sha256"]]))
        unknown = [label for key, label in SETTING_LABELS.items() if key != "fee_schedule_sha256" or not old_version]
        out.append(summary.settings_unverified_caveat(list(unverified) + unknown + ["运行环境的版本"]))
        return out
    changed = [label for key, label in SETTING_LABELS.items() if key in before and before.get(key) != after.get(key)]
    if changed:
        out.append(summary.settings_changed_caveat(changed))
    if unverified:
        out.append(summary.settings_unverified_caveat(list(unverified)))
    if "runtime" in before and before.get("runtime") != after.get("runtime"):
        out.append(summary.runtime_changed_caveat(before.get("runtime"), after.get("runtime")))
    return out


_CONTROL = re.compile(r"[\x00-\x1f\x7f\u2028\u2029]+")


def _one_line(text, limit: int) -> str:
    text = _CONTROL.sub(" ", str(text)).strip()
    return text if len(text) <= limit else text[:limit - 1] + "…"


def reflection_payload(result: Dict[str, Any]) -> Dict[str, Any]:
    """What the reflector reads of a RunResult: a copy whose free text (names from the
    ledger, strategy names and parameters, symbols, caveat texts, the headline) is one
    line without control characters and of bounded length. Numbers are unchanged; the
    stored result is not touched. The reflector then shows every such text to the model
    only as {"untrusted_text": ...} (llm_reflector.prompt_sections)."""
    payload = copy.deepcopy(result)
    facts = payload.get("facts") or {}
    for key in ("name", "label", "index_name"):
        if isinstance(facts.get(key), str):
            facts[key] = _one_line(facts[key], 60)
    strategy = facts.get("strategy") if isinstance(facts.get("strategy"), dict) else {}
    for key in ("name", "id", "class"):
        if isinstance(strategy.get(key), str):
            strategy[key] = _one_line(strategy[key], 60)

    def clean(value):
        if isinstance(value, str):
            return _one_line(value, 60)
        if isinstance(value, dict):
            return {_one_line(k, 60): clean(v) for k, v in value.items()}
        if isinstance(value, list):
            return [clean(v) for v in value]
        return value

    if "params" in strategy:
        strategy["params"] = clean(strategy["params"])
    for caveat in payload.get("caveats") or []:
        if isinstance(caveat, dict) and isinstance(caveat.get("text"), str):
            caveat["text"] = _one_line(caveat["text"], 400)
    for trip in payload.get("round_trips") or []:
        if isinstance(trip, dict) and isinstance(trip.get("symbol"), str):
            trip["symbol"] = _one_line(trip["symbol"], 40)
    if isinstance(payload.get("headline_zh"), str):
        payload["headline_zh"] = _one_line(payload["headline_zh"], 600)
    return payload


