    def build_result(self, plan: Plan, engine: BacktestEngine, result,
                     bars: Optional[pd.DataFrame] = None) -> Dict[str, Any]:
        """bars: the traded symbol's frame as handed to the strategy, frozen before the run
        (default: engine.loaded_frame(plan.label))."""
        if bars is None:
            bars = engine.loaded_frame(plan.label)
        stats = result.stats
        # Every figure in the facts is the metrics' own value: null (with the reason in
        # metrics.undefined) where the statistic has none, never a stand-in 0.
        statistics = stats.to_dict()
        equity = equity_rows(result)
        period = result.period
        first, last = period["first_date"], period["last_date"]
        coverage = engine.coverage[plan.label]

        same_part = same_stock_benchmark(engine, plan, bars)
        same_return = same_part["total_return"]
        index_part, index_reason, index_coverage = (None, None, None)
        if plan.benchmark is not None and first and last:
            index_part, index_reason, index_coverage = self._index_benchmark(engine, plan, equity)
        elif plan.demo and (plan.benchmark_choice or "auto").strip().lower() != "none":
            index_reason = "演示模式没有指数行情，没有和大盘指数比较。"

        peak, trough = drawdown_dates(equity)
        marks = end_mark_positions(result)
        trips = [with_end_mark(trip, marks) for trip in result.round_trips]
        closed = [trip for trip in trips if not trip["end_mark"]]
        lot = market_rules.lot_rule(plan.symbol.ticker, plan.market_code, plan.broker.get("lot_size"))
        default_rate, default_min = default_schedule().commission_default(plan.market_code)
        facts = {
            "ticker": plan.symbol.ticker, "label": plan.label, "name": plan.name,
            "market": plan.symbol.market, "market_label": summary.MARKET_LABELS[plan.symbol.market],
            "currency": plan.symbol.currency, "kind": plan.symbol.kind, "source": coverage.source,
            "demo": plan.demo,
            "strategy": {k: plan.strategy_info.get(k) for k in ("kind", "id", "name", "class", "params")},
            "period": {"preset": plan.period_preset, "requested_start": plan.start,
                       "requested_end": plan.requested_end or plan.end, "first_date": first, "last_date": last,
                       "calendar_days": period["calendar_days"], "bars": period["bars"],
                       "span_label": summary.span_label(first, last) if first and last else None},
            "first_date": first, "last_date": last,
            "capital": plan.capital, "final_value": statistics["final_value"],
            "total_return": statistics["total_return"], "annualized_return": statistics["annualized_return"],
            "same_stock_return": same_return,
            "same_stock_reason": same_part["reason"],
            "index_ticker": plan.benchmark, "index_name": INDEX_NAMES.get(plan.benchmark) if plan.benchmark else None,
            "index_return": index_part["total_return"] if index_part else None,
            "index_reason": None if index_part else index_reason,
            "max_drawdown": statistics["max_drawdown"], "max_drawdown_peak": peak, "max_drawdown_trough": trough,
            "closed_trades": len(closed), "winning_trades": stats.winning_trades,
            "losing_trades": stats.losing_trades, "open_at_end": sum(1 for trip in trips if trip["end_mark"]),
            "fills": len(result.trades), "fees_total": result.fees_total,
            # The hypothetical end-of-data liquidation (not a sale), with why it could not
            # really happen: positions[].blocked / blocked_quantity / blocked_zh.
            "end_mark": ({**result.end_mark, "positions": list(marks.values())} if result.end_mark else None),
            "adjust": plan.adjust, "warmup_bars": plan.warmup, "warmup_auto": plan.warmup_auto,
            "lot": {"minimum": lot.minimum, "step": lot.step, "assumed": lot.assumed,
                    "override": plan.broker.get("lot_size")},
            "commission": {"buy": plan.broker.get("commission_buy"), "sell": plan.broker.get("commission_sell"),
                           "min": plan.broker.get("min_commission"), "default_rate": float(default_rate),
                           "default_min": float(default_min), "defaulted": plan.commission_defaulted,
                           "sell_rate_includes": plan.broker.get("sell_rate_includes") or []},
            "slippage_pct": plan.broker.get("slippage_pct"),
        }
        headline, missing = summary.headline(facts)
        caveats = list(result.caveats) + missing
        if not _holds_to_end(plan):
            # Plain buy and hold has no parameter to tune on this history: nothing to act on.
            caveats.append(summary.in_sample_caveat())
        if plan.legacy_fees:
            caveats.append(summary.legacy_fees_caveat(plan.legacy_fees))
        if plan.commission_defaulted:
            caveats.append(summary.commission_caveat(plan.symbol.market, float(default_rate), float(default_min),
                                                     plan.symbol.currency))
        # The traded symbol's bars as handed to the strategy, derived features included: the
        # repository's sha256 covers the bars only, and the features come from code.
        traded = {**coverage.to_dict(), "features_sha256": bars_sha256(bars)}
        coverage_list = [traded] + ([{**index_coverage, "features_sha256": None}] if index_coverage else [])
        manifest = {
            "engine_version": ENGINE_VERSION,
            "spec": plan.spec_record(),
            "coverage": coverage_list,
            "fee_schedule_version": default_schedule().version,
            "data_sha256": combined_sha256(coverage_list),
            "data_hash_version": DATA_HASH_VERSION,
            "created_at": datetime.now().isoformat(timespec="seconds"),
            "demo": plan.demo,
            "rerun_of": plan.rerun_of,
            "resolved": resolved_settings(plan),
        }
        # A rerun reproduces the bars actually used: the end is the last bar, not "today"
        # (today's bar is not complete when the run is made, and would be later).
        if last:
            manifest["spec"]["period"]["end"] = last
        if plan.original is not None:
            before = plan.original.get("manifest") or {}
            caveats += (rerun_caveats(plan.original, manifest) + list(plan.rerun_notes)
                        + settings_caveats(before.get("resolved"), manifest["resolved"], before_manifest=before,
                                           unverified=plan.original.get("unverified_settings") or ()))
        return _jsonable({
            "run_id": plan.run_id,
            "created_at": manifest["created_at"],
            "facts": facts,
            "headline_zh": headline,
            "caveats": summary.sort_caveats(caveats),
            "metrics": with_executable_benchmark(statistics, same_part),
            "metric_notes": summary.METRIC_NOTES,
            "equity": equity,
            "benchmark": {
                "same_stock": same_part,
                "index": index_part,
            },
            "round_trips": [{**trip, "exit_reason_zh": summary.EXIT_REASON_ZH.get(trip.get("exit_reason"),
                                                                                    trip.get("exit_reason"))}
                            for trip in trips],
            "fills": fill_rows(result, marks),
            "unfilled": [{**entry, "reason_zh": UNFILLED_REASON_ZH.get(entry.get("reason"), entry.get("reason"))}
                         for entry in result.unfilled],
            "monthly_returns": monthly_returns(equity, plan.capital),
            "prices": price_rows(engine, plan.label, bars),
            "warmup": {**(result.warmup_info.get(plan.label) or {}), "auto": plan.warmup_auto},
            "assumptions": {**result.to_dict()["assumptions"], "slippage_pct": plan.broker.get("slippage_pct"),
                            "line_zh": assumptions_line(plan, first or plan.start, last or plan.end)},
            "rerun": {**rerun_summary(plan.original, manifest, with_executable_benchmark(statistics, same_part)),
                      "same_strategy": plan.same_strategy} if plan.original else None,
            "manifest": manifest,
        })

    def _index_benchmark(self, engine: BacktestEngine, plan: Plan, equity: List[Dict[str, Any]]):
        name = INDEX_NAMES.get(plan.benchmark, plan.benchmark)
        first, last = equity[0]["date"], equity[-1]["date"]
        lo = (pd.Timestamp(first) - pd.Timedelta(days=15)).strftime("%Y-%m-%d")
        try:
            bars, coverage = engine.repository.load(plan.benchmark, lo, last, adjust="")
        except (BarsUnavailableError, ValueError) as exc:
            logger.info("[Backtest] index %s unavailable (%s)", plan.benchmark, type(exc).__name__)
            return None, f"{name} 行情无法获取（本地没有，下载也没有成功），没有和指数比较；指数一栏显示为不可用，不是 0。", None
        closes = bars["close"].astype(float)
        closes.index = pd.DatetimeIndex(closes.index).normalize()
        closes = closes[~closes.index.duplicated(keep="last")].dropna()
        days = [row["date"] for row in equity]
        index_market = resolve(plan.benchmark).market
        gaps, closed, contradicted = index_session_gaps(
            days, [day.strftime("%Y-%m-%d") for day in closes.index],
            same_calendar=index_market == plan.symbol.market, index_market=index_market)

        def listed(dates):
            return "、".join(dates[:5]) + (f" 等 {len(dates)} 天" if len(dates) > 5 else "")

        # The index's own bars must be as trustworthy as the run's: a splice of two downloads
        # (a false jump at the seam) or provisional bars dropped inside the run is no comparison.
        if coverage.unverified or coverage.splice_seams:
            seams = list(coverage.splice_seams or coverage.unverified)
            return None, (f"{name} 的行情在 {listed(seams)} 处由本地缓存里两次下载拼接而成，无法核对复权锚点，"
                          f"拼接处可能有假的涨跌；没有和指数比较。指数一栏显示为不可用，不是 0。"), coverage.to_dict()
        dropped = [day for day in coverage.dropped_provisional or [] if first <= day <= last]
        if dropped:
            return None, (f"{name} 在 {listed(dropped)} 的 K 线是收盘前取得的临时数据，已去掉，也没能重新下载；"
                          f"这些天没有指数的最终行情，没有和指数比较。指数一栏显示为不可用，不是 0。"), coverage.to_dict()
        if gaps:
            unknown = sorted({pd.Timestamp(day).year for day in gaps
                              if index_market != plan.symbol.market and index_market_closed(day, index_market) is None})
            why = (f"（这些是回测期间的交易日；{'、'.join(map(str, unknown))} 年没有{name}所在市场的休市表，"
                   f"无法确认这些天休市）" if unknown else f"（这些是回测期间的交易日，不是{name}所在市场的休市日）")
            return None, (f"{name} 在 {listed(gaps)} 没有行情{why}，"
                          f"本地有 {coverage.first}~{coverage.last}；不能用前一天的收盘价代替，没有和指数比较。"
                          f"指数一栏显示为不可用，不是 0。"), coverage.to_dict()
        if contradicted:
            return None, (f"{name} 在 {listed(contradicted)} 有行情，但按休市表那几天{name}所在市场休市；"
                          f"指数数据与交易日历矛盾，没有和指数比较。指数一栏显示为不可用，不是 0。"), coverage.to_dict()
        aligned = closes.reindex(closes.index.union(pd.DatetimeIndex([pd.Timestamp(day) for day in days])))
        aligned = aligned.ffill()                    # only the closures index_session_gaps confirmed
        base = float(closes[closes.index <= pd.Timestamp(days[0])].iloc[-1])
        curve = [{"date": day, "value": round(float(aligned[pd.Timestamp(day)]) / base, 6)} for day in days]
        part = {"ticker": plan.benchmark, "name": name, "total_return": round(curve[-1]["value"] - 1.0, 6),
                "curve": curve, "source": coverage.source, "offline": coverage.offline,
                "closed_dates": closed}
        return part, None, coverage.to_dict()

