def lot_text(lot) -> str:
    if lot.assumed:
        return f"每手按 {lot.minimum} 股（请核对）"
    if lot.minimum == lot.step == 1:
        return "按 1 股交易"
    if lot.step == 1:
        return f"最少 {lot.minimum} 股，之后 1 股递增"
    return f"每手 {lot.minimum} 股"


