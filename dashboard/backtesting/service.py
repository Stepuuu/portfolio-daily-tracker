def _jsonable(value):
    if isinstance(value, dict):
        return {str(k): _jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(v) for v in value]
    if isinstance(value, float) and not math.isfinite(value):
        return None
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    if hasattr(value, "item") and not isinstance(value, (bytes, bytearray)):
        try:                               # numpy scalars
            return _jsonable(value.item())
        except (TypeError, ValueError):
            pass
    return str(value)


_LOOKBACK_KEY = re.compile(r"(period|window|days|lookback|length)$", re.IGNORECASE)


def auto_warmup(strategy_cls, kwargs: Dict[str, Any]) -> int:
    """Warm-up bars for a strategy: its own `warmup_bars` if it declares one; none when
    it says these kwargs need none (`needs_warmup(kwargs)`: a rule that reads no
    indicator, such as 一直持有); else 1.2x the longest lookback-like integer
    parameter (+5), at least 60."""
    declared = getattr(strategy_cls, "warmup_bars", None)
    if isinstance(declared, int) and not isinstance(declared, bool) and declared >= 0:
        return min(declared, MAX_WARMUP)
    needs = getattr(strategy_cls, "needs_warmup", None)
    if callable(needs):
        try:
            if not needs(kwargs):
                return 0
        except ValueError:
            pass                       # an invalid spec is refused when the strategy starts
    longest = 0

    def scan(value, key=""):
        nonlocal longest
        if isinstance(value, dict):
            for k, v in value.items():
                scan(v, str(k))
        elif isinstance(value, (list, tuple)):
            for v in value:
                scan(v, key)
        elif isinstance(value, (int, float)) and not isinstance(value, bool) and _LOOKBACK_KEY.search(key):
            if math.isfinite(float(value)):
                longest = max(longest, int(value))

    scan({**(getattr(strategy_cls, "parameters", None) or {}), **kwargs})
    return int(min(MAX_WARMUP, max(DEFAULT_WARMUP, math.ceil(longest * 1.2) + 5)))


def _holds_to_end(plan) -> bool:
    """The plan runs a rule that buys once and never sells (rules.holds_to_end)."""
    from backtesting.strategies.rules import RuleStrategy, holds_to_end, normalize_spec
    spec = (plan.strategy_kwargs or {}).get("spec")
    if not (isinstance(plan.strategy_cls, type) and issubclass(plan.strategy_cls, RuleStrategy)
            and isinstance(spec, dict)):
        return False
    try:
        return holds_to_end(normalize_spec(spec))
    except ValueError:
        return False


