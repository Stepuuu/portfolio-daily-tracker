    #  Running
    # ------------------------------------------------------------ #

    def start(self, plan: Plan, kind: str = "run", reflect_after: bool = False) -> RunTask:
        """Run in a background thread. reflect_after: start the AI reading once the run is done
        (it never delays the result)."""
        task = self.registry.add(RunTask(plan.run_id, kind))
        thread = threading.Thread(target=self._work, args=(task, plan, reflect_after), daemon=True,
                                  name=f"backtest-{plan.run_id}")
        try:
            thread.start()
        except RuntimeError:               # no thread for it: failed, never left "queued"
            logger.exception("[Backtest] run %s could not start", plan.run_id)
            self._finish(task, status="failed", error={"status": 503, "message": "服务器暂时不能开始新的回测，请稍后再试"})
            raise UserError("服务器暂时不能开始新的回测，请稍后再试", 503) from None
        return task

    def run_inline(self, plan: Plan, kind: str = "legacy", reflect_after: bool = False) -> RunTask:
        """Run in the calling thread (legacy /run-sync); the task is visible in the registry."""
        task = self.registry.add(RunTask(plan.run_id, kind))
        self._work(task, plan, reflect_after)
        return task

    def _work(self, task: RunTask, plan: Plan, reflect_after: bool = False) -> None:
        task.update(status="running", started_at=datetime.now().isoformat(timespec="seconds"))
        final: Dict[str, Any] = {}
        try:
            # A cancel that arrives after the simulation finished is too late: the
            # result may already be saved, so it is reported as completed.
            result, legacy = self.execute(plan, task)
            with task.lock:                 # the result, its status and a pending reading appear together
                task.update(result=result, legacy={**legacy, "reflection_status": "pending"} if reflect_after
                            else legacy, saved=bool(legacy.get("saved_to_history")), status="completed")
                if reflect_after:
                    task.set_reflection({"status": "pending", "result": None, "message": None})
                    task.reflection_done.clear()
            if reflect_after:
                self._start_reflection(task)
        except RunCancelled:
            final = {"status": "cancelled"}
        except UserError as exc:
            final = {"status": "failed", "error": {"status": exc.status, "message": exc.message}}
        except (MarketDataUnavailableError, BarsUnavailableError) as exc:
            final = {"status": "failed", "error": {"status": 422, "message": f"没有取到行情：{exc}"}}
        except BaseException as exc:   # an internal error: logged, never echoed; the worker ends cleanly
            logger.exception("[Backtest] run %s failed", plan.run_id)
            final = {"status": "failed",
                     "error": {"status": 500, "message": f"回测内部错误（{type(exc).__name__}），详情见服务端日志"}}
        finally:
            self._finish(task, **final)

    def _finish(self, task: RunTask, **final) -> None:
        """The last state of a run: whatever happened, it is finished and done_event is set."""
        with task.lock:
            if final:
                task.update(**final)
            if not task.finished:           # nothing above set a final state
                task.update(status="failed", error=task.error or {
                    "status": 500, "message": "回测内部错误（未知），详情见服务端日志"})
            task.update(stage="done" if task.status == "completed" else task.stage,
                        finished_at=datetime.now().isoformat(timespec="seconds"))
        task.done_event.set()
        try:
            self.registry.evict()
        except Exception:
            logger.exception("[Backtest] registry eviction failed")

    def _loader(self, plan: Plan, now):
        if self.loader_factory is not None:
            return self.loader_factory(plan)
        if plan.demo:
            from backtesting.demo import DemoLoader
            return DemoLoader(now=now)
        return None

    def execute(self, plan: Plan, task: Optional[RunTask] = None) -> Tuple[Dict[str, Any], Dict[str, Any]]:
        """Run the plan: (RunResult, legacy response dict). Saves to history when plan.save."""
        task = task or RunTask(plan.run_id)
        now = self._now_fn()
        task.report("prepare_data")

        def progress(stage, detail=None):
            if plan.demo and stage == "prepare_data":
                detail = "demo"
            task.report(stage, detail)

        # In demo mode the loader is DemoLoader ("downloading" generates synthetic bars, no
        # network) and the run completes in memory: no bar cache is read, written or created.
        engine = BacktestEngine(
            initial_cash=plan.capital, broker_config=make_broker_config(plan.broker),
            use_cache=not plan.demo, loader=self._loader(plan, now), now=now, run_id=plan.run_id,
            progress=progress, should_stop=task.cancelled,
        )
        engine.add_data(plan.label, plan.start, plan.end, adjust=plan.adjust, warmup=plan.warmup,
                        ticker=plan.symbol, allow_partial=True)
        coverage = engine.coverage[plan.label]
        if plan.adjust == "" and coverage.suspected_corporate_actions and not plan.allow_unadjusted:
            dates = "、".join(coverage.suspected_corporate_actions[:5])
            raise UserError(
                f"不复权价格在 {dates} 有疑似除权或拆合股的跳空，回测会把它当成真实涨跌；请改用前复权 (qfq)，"
                f"或确认后设置 allow_unadjusted=true 再运行（结果会带上提醒）。")
        engine.add_strategy(plan.strategy_cls, **plan.strategy_kwargs)
        task.report("simulate", 0.0)
        result = engine.run()
        if task.cancelled():
            raise RunCancelled("回测已取消")
        task.report("stats")
        # The bars as handed to the strategy (warm-up and derived features included), frozen
        # by the engine before any strategy ran: whatever the strategy did to its frame never
        # reaches the comparison, the prices or the data fingerprint.
        run_result = self.build_result(plan, engine, result, bars=engine.loaded_frame(plan.label))
        legacy = legacy_response(plan, result, run_result)
        if plan.save:
            legacy["saved_to_history"] = self._save(plan, result, run_result, legacy)
        else:
            legacy["saved_to_history"] = False
        return run_result, legacy

    def _now_fn(self):
        today = self.today()
        if today == date.today():
            return None                                  # the repository's own clock
        moment = pd.Timestamp(today) + pd.Timedelta(hours=18)
        return lambda: moment

    def _save(self, plan: Plan, result, run_result: Dict[str, Any], legacy: Dict[str, Any]) -> bool:
        try:
            history = self.history_factory()
            name = plan.strategy_info["name"] if plan.strategy_info["kind"] == "preset" else result.strategy_name
            record = {**legacy, "strategy_name": name, "run_date": result.run_date,
                      "start_date": plan.start, "end_date": plan.end if plan.legacy else
                      (run_result["facts"]["last_date"] or plan.end)}
            history.save_run(
                result_dict=record,
                reflection=None,
                equity_curve=legacy["equity_curve"],
                trades=run_result["fills"],
                broker_config={key: plan.broker.get(key) for key in
                               ("commission_buy", "commission_sell", "min_commission", "slippage_pct", "lot_size")},
                tags=plan.tags,
                notes=plan.notes,
                manifest=run_result["manifest"],
                result=run_result,
            )
            return True
        except Exception as exc:
            logger.warning("[Backtest] 保存回测历史失败 (%s)", type(exc).__name__)
            return False

