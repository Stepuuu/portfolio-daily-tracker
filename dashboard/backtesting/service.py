    def _symbol(self, text, demo: bool) -> Tuple[Symbol, Optional[str]]:
        if demo:
            from backtesting.demo import demo_symbol, demo_tickers
            tickers = demo_tickers()
            key = str(text).strip().upper().replace("：", ":")
            if key not in tickers:
                allowed = "、".join(tickers) or "无"
                raise UserError(f"演示模式只能回测演示持仓里的标的：{allowed}", 403)
            return demo_symbol(key), tickers[key]["name"]
        try:
            symbol = resolve(text)
        except SymbolError as exc:
            raise UserError(str(exc)) from None
        if symbol.kind == INDEX:
            raise UserError(f"{symbol.ticker} 是指数，不能直接买卖；请回测跟踪它的 ETF（例如沪深300 可用 SHA:510300）")
        return symbol, instrument_name(symbol.ticker)

    def _strategy(self, preset: Optional[str], strategy: Optional[str], params: Dict[str, Any], legacy: bool):
        if bool(preset) == bool(strategy):
            raise UserError("请在预设方法 (preset) 和策略 (strategy) 中选一个")
        if not isinstance(params, dict):
            raise UserError("参数 (params) 必须是对象")
        if preset:
            module = self.presets_loader()
            if module is None:
                raise UserError(PRESETS_MISSING, 503)
            cls, kwargs = _preset_call(module.build, preset, params)
            names = {item["id"]: item["name"] for item in _describe(module)}
            # The resolved spec: what build() made (RuleStrategy's spec), else spec() once.
            resolved = kwargs.get("spec") if isinstance(kwargs, dict) and isinstance(kwargs.get("spec"), dict) else None
            spec_fn = getattr(module, "spec", None)
            if resolved is None and callable(spec_fn):
                resolved = _preset_call(spec_fn, preset, params)
            info = {"kind": "preset", "id": preset, "name": names.get(preset, preset), "class": cls.__name__,
                    "params": _jsonable(dict(params)), "resolved": _jsonable(resolved) if resolved else None}
            return cls, dict(kwargs), info
        if self.strategy_resolver is None:
            raise UserError("没有可用的策略列表", 503)
        try:
            cls = self.strategy_resolver(strategy)
        except ValueError as exc:
            raise UserError(str(exc)) from None
        kwargs = check_strategy_params(cls, params, strict=not legacy)
        info = {"kind": "strategy", "id": strategy, "name": getattr(cls, "name", cls.__name__),
                "class": cls.__name__, "params": _jsonable(kwargs)}
        return cls, kwargs, info

    def _benchmark(self, choice: str, symbol: Symbol) -> Optional[str]:
        value = (choice or "auto").strip()
        if value.lower() == "auto":
            return INDEX_BENCHMARKS.get(symbol.market)
        if value.lower() == "none":
            return None
        try:
            index = resolve(value)
        except SymbolError as exc:
            raise UserError(f"对比基准: {exc}") from None
        if index.kind != INDEX:
            raise UserError("对比基准只能是 auto、none 或指数代码（如 IDX:000300）")
        return index.ticker

    @_planning
    def plan(self, spec: RunSpec, *, run_id: Optional[str] = None) -> Plan:
        demo = storage.demo_mode()
        symbol, name = self._symbol(spec.ticker, demo)
        cls, kwargs, info = self._strategy(spec.preset, spec.strategy, spec.params, legacy=False)
        today = self.today()
        if spec.period == "custom":
            if not spec.start_date:
                raise UserError("自定义区间需要开始日期 (start_date)")
            start = date.fromisoformat(spec.start_date)
            end = date.fromisoformat(spec.end_date) if spec.end_date else today
        else:
            if spec.start_date or spec.end_date:
                raise UserError(f"区间 {spec.period} 按今天自动计算；要指定日期请把 period 设为 custom")
            end = today
            start = years_before(today, PERIOD_YEARS[spec.period])
        entry_day = preset_entry_day(info)
        if entry_day:
            if entry_day > end:
                raise UserError(f"买入日期 {entry_day} 晚于回测结束日期 {end}")
            if entry_day < start:
                if spec.period == "custom":
                    raise UserError(f"买入日期 {entry_day} 早于回测开始日期 {start}；请把开始日期提前")
                start = entry_day           # a holding is backtested from its entry date
        if end > today:
            end = today
        if start >= end:
            raise UserError(f"开始日期 {start} 必须早于结束日期 {end}")
        commission_buy = spec.commission_buy if spec.commission_buy is not None else spec.commission_rate
        commission_sell = spec.commission_sell if spec.commission_sell is not None else spec.commission_rate
        warmup = spec.warmup if spec.warmup is not None else auto_warmup(cls, kwargs)
        benchmark = self._benchmark(spec.benchmark, symbol)       # an invalid choice is refused, demo or not
        if demo:
            benchmark = None        # the demo has no index bars and opens no bar cache, whichever index is asked for
        return Plan(
            run_id=run_id or new_run_id(), label=symbol.ticker, symbol=symbol, name=name,
            strategy_cls=cls, strategy_kwargs=kwargs, strategy_info=info,
            definition=strategy_definition(cls, kwargs, info),
            period_preset=spec.period, start=start.isoformat(), end=end.isoformat(),
            requested_end=end.isoformat(),
            capital=float(spec.capital) if spec.capital is not None else DEFAULT_CAPITAL,
            broker={"commission_buy": commission_buy, "commission_sell": commission_sell,
                    "min_commission": spec.min_commission,
                    "slippage_pct": spec.slippage_pct if spec.slippage_pct is not None else DEFAULT_SLIPPAGE,
                    "lot_size": spec.lot_size, "market": MARKET_CODES[symbol.market]},
            commission_defaulted=commission_buy is None and commission_sell is None and spec.min_commission is None,
            adjust=spec.adjust, allow_unadjusted=spec.allow_unadjusted,
            benchmark_choice=spec.benchmark, benchmark=benchmark,
            warmup=warmup, warmup_auto=spec.warmup is None,
            # A demo run completes in memory: it is never saved, whatever the request says.
            tags=list(spec.tags), notes=spec.notes, save=spec.save and not demo, demo=demo,
        )

    @_planning
    def plan_legacy(self, req, *, run_id: Optional[str] = None) -> Plan:
        """The legacy BacktestRequest as a plan: dates and strategy as sent, label as typed."""
        demo = storage.demo_mode()
        symbol, name = self._symbol(req.symbol, demo)
        cls, kwargs, info = self._strategy(None, req.strategy, req.params, legacy=True)
        try:
            start, end = parse_day(req.start_date), parse_day(req.end_date)
        except ValueError as exc:
            raise UserError(str(exc)) from None
