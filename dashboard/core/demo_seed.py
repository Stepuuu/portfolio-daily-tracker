"""Seed a demo portfolio directory with scripted quotes and, on request, a ledger and a desk.

Called by ``engine/scripts/create_demo.py`` on the fictional portfolio it has
just written. Everything here is synthetic: invented tickers, names, prices
and balances. Nothing is read from, or written to, a real portfolio.

Without ``ledger`` only ``fake_quotes.json`` is written: the default demo
starts from an empty ledger (the opening-balance journey) and has no
``desk.sqlite3``. With it, the directory also gets what the daily-desk pages
show, written through the features' own public functions so that their
validation, plan and alert rules apply:

* the ledger: the opening balance, then a few events on past trading days
  (``seed_ledger``);
* the desk store: a watchlist, trade plans, alert rules with one fired alert,
  and one pending proposal (``seed_desk``);
* a pre-market and a post-market brief of the last trading day before the
  demo is made, generated by the brief builders from this data (``seed_briefs``).

Dates are relative to the day the demo is created: every event, plan and
alert is placed on one of the last trading days before it (mainland calendar
of ``core.market.calendar``), so the demo looks current whenever it is made.
"""
from __future__ import annotations

import json
import os
from contextlib import contextmanager
from datetime import date, datetime, time, timedelta
from pathlib import Path
from typing import Dict, Iterator, Mapping, Optional

from core.ledger import Ledger
from core.market.sources_fake import FILE_NAME

LONG_ACCOUNT, RESEARCH_ACCOUNT = '长期账户', '研究账户'

# Scripted quotes of tickers the demo does not hold: watched ones, the one a
# closed plan was about, the one a proposal suggests. ``NASDAQ:DEMOY`` has none
# on purpose, so the watchlist shows an unavailable quote.
EXTRA_QUOTES = {
    'NASDAQ:DEMOW': {'name': '示例成长股', 'price': '48.2', 'prev_close': '47.6'},
    'NYSE:DEMOX': {'name': '示例价值股', 'price': '31.4', 'prev_close': '31.55'},
    'NYSE:DEMOV': {'name': '示例消费股', 'price': '22.85', 'prev_close': '22.9'},
    'SHE:DEMOZ': {'name': '示例周期股', 'price': '13.62', 'prev_close': '13.55'},
}


def _text(value) -> str:
    return format(round(float(value), 4), 'f').rstrip('0').rstrip('.') or '0'


def write_fake_quotes(directory, holdings: Mapping, prices: Mapping, rates: Mapping,
                      previous_prices: Optional[Mapping] = None,
                      extra_quotes: Optional[Mapping[str, Mapping]] = None) -> Path:
    """Write ``fake_quotes.json`` with one quote per ticker in ``holdings``.

    ``extra_quotes`` adds tickers that are not held: ``{ticker: {name, price, prev_close}}``.

    Timestamps are relative (``age_seconds``), so the demo shows a fresh
    quote whenever it is opened instead of one that has gone stale on disk.
    """
    previous_prices = previous_prices or {}
    quotes = {}
    for group in holdings.get('groups', {}).values():
        for position in group.get('positions', []):
            ticker = position['ticker']
            quotes[ticker] = {'name': position.get('name', ticker), 'price': _text(prices[ticker]),
                              'prev_close': _text(previous_prices.get(ticker, prices[ticker])), 'age_seconds': 3}
    for ticker, entry in (extra_quotes or {}).items():
        quotes[ticker] = {'name': entry['name'], 'price': _text(entry['price']),
                          'prev_close': _text(entry.get('prev_close', entry['price'])), 'age_seconds': 3}
    script = {'quotes': quotes,
              'fx': {currency: {'rate': _text(rate), 'age_seconds': 5}
                     for currency, rate in rates.items() if currency != 'CNY'}}
    path = Path(directory) / FILE_NAME
    path.write_text(json.dumps(script, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return path


def seed_ledger(directory, holdings: Mapping, opened_on: str) -> int:
    """Confirm an opening balance equal to ``holdings``; return the revision.

    It goes through the same preview-and-confirm path as a real entry.
    """
    events = []
    for name, group in holdings.get('groups', {}).items():
        balances = group.get('cash_balances', {'CNY': group.get('cash', 0)})
        events.append({
            'kind': 'opening', 'date': opened_on, 'account': name, 'source': 'demo',
            'external_id': f'demo-opening:{name}', 'note': '演示数据：虚构的期初余额',
            'cash_balances': {currency: _text(balance) for currency, balance in balances.items()},
            'positions': [{'ticker': position['ticker'], 'name': position.get('name', position['ticker']),
                           'quantity': _text(position['quantity']), 'cost_price': _text(position['cost_price'])}
                          for position in group.get('positions', [])],
            'contributed_cny': _text(group.get('cost_basis', 0)), 'fund_cny': _text(group.get('fund', 0))})
    ledger = Ledger(Path(directory) / 'ledger.sqlite3')
    from core import desk_store
    with desk_store.pinned_now(_at(date.fromisoformat(opened_on), 9, 0)):
        return ledger.confirm(ledger.propose(events)['id'])['revision']


# -- dates ----------------------------------------------------------------------

HISTORY_DAYS = 12          # the oldest thing the seed writes is on the 12th trading day back


def history_days(today: Optional[date] = None, last_snapshot: Optional[date] = None) -> Dict[int, date]:
    """``{k: the k-th mainland trading day before today}`` for k = 1..``HISTORY_DAYS``.

    Weekdays that the shipped holiday table does not close, so no seeded event
    falls on a Saturday or a known holiday. ``today`` defaults to today in
    Shanghai. The history must follow the demo's opening balance: when the
    oldest day would be on or before ``last_snapshot`` this raises
    ``ValueError`` (``create_demo`` places the snapshots before the history,
    so it never does); the days are never moved past ``today``, which would
    date the events in the future.
    """
    from core.market.calendar import CN, SHANGHAI, SessionClock
    today = today or datetime.now(SHANGHAI).date()
    clock = SessionClock()
    days, day = {}, today
    try:
        for k in range(1, HISTORY_DAYS + 1):
            day = clock.previous_trading_day(CN, day)
            days[k] = day
    except OverflowError:
        raise ValueError(f'cannot make the demo for {today}: its history starts {HISTORY_DAYS} trading days earlier, '
                         f'before {date.min}, the first date there is') from None
    if last_snapshot is not None and days[HISTORY_DAYS] <= last_snapshot:
        raise ValueError(f'the demo history for {today} would start on {days[HISTORY_DAYS]}, not after the last '
                         f'snapshot on {last_snapshot}: make the demo for a later day, or with snapshots ending earlier')
    return days


def _at(day: date, hour: int, minute: int = 0) -> datetime:
    from core.market.calendar import SHANGHAI
    return datetime.combine(day, time(hour, minute), tzinfo=SHANGHAI)


@contextmanager
def _portfolio(directory) -> Iterator[None]:
    """Point the desk features (which follow ``PORTFOLIO_DIR``) at ``directory`` for a while."""
    previous = os.environ.get('PORTFOLIO_DIR')
    os.environ['PORTFOLIO_DIR'] = str(directory)
    try:
        yield
    finally:
        if previous is None:
            os.environ.pop('PORTFOLIO_DIR', None)
        else:
            os.environ['PORTFOLIO_DIR'] = previous


# -- the desk -------------------------------------------------------------------

def _trade(day: date, kind: str, ticker: str, name: str, quantity, price, fee, key: str, note: str) -> dict:
    return {'kind': kind, 'date': day.isoformat(), 'account': LONG_ACCOUNT, 'ticker': ticker, 'name': name,
            'currency': 'CNY', 'quantity': _text(quantity), 'price': _text(price), 'fee': _text(fee),
            'source': 'demo', 'external_id': f'demo-trade:{key}', 'note': f'演示数据：{note}'}


def _cash(day: date, kind: str, account: str, amount, key: str, note: str, **more) -> dict:
    return {'kind': kind, 'date': day.isoformat(), 'account': account, 'currency': 'CNY', 'amount': _text(amount),
            'source': 'demo', 'external_id': f'demo-cash:{key}', 'note': f'演示数据：{note}', **more}


def seed_desk(directory, holdings: Mapping, today: Optional[date] = None) -> None:
    """Write the demo's history into the ledger and ``desk.sqlite3``; needs the opening balance.

    Oldest first, each step stamped with its own day (``desk_store.pinned_now``)
    so that plan activations, rule creations and the fired alert come in the
    order they would have happened. k-th trading day back is written ``Dk``:

    ======  ======================================================================
    D12     plan #1 for ``SHE:DEMOZ`` (stop 11.2, target 13.5) is written and activated
    D11     the ledger buys 500 ``SHE:DEMOZ`` at 12.3: an entry under plan #1
    D10     four tickers go on the watchlist
    D9      plan #2 for ``SHA:DEMO`` (stop 54, target 66) is written and activated
    D8      the ledger buys 200 ``SHA:DEMO`` at 58.8: an add under plan #2
    D7      a dividend of 360 on the 1200 ``SHA:DEMO``
    D6      two rules of the person's own: a day-change and a position-weight rule
    D5      the ledger sells all ``SHE:DEMOZ`` at 13.6 (the target) and plan #1 is closed
    D4      an account fee and a repo interest credit
    D3      10:42, the weight rule fires: ``SHA:DEMO`` is 57.9 % of the portfolio, the limit 50 %
    D2      a draft plan for the watched ``NYSE:DEMOX``
    D1      20:30, an assistant's proposal to watch ``NASDAQ:DEMOQ``; it waits for confirmation
    ======  ======================================================================

    Nothing is dated after ``today``; the plans' review dates, about two weeks
    after D1, are deadlines rather than records. A ``today`` too close to the
    end of the calendar for them (year 9999) is a ``ValueError``, raised
    before anything is written (``check_history``).

    The fired alert is decided by ``core.alerts.engine`` on the scripted quotes
    of ``fake_quotes.json`` with the clock set to D3 10:42, so it is true of
    the prices the demo shows. Trades stay on D4 or earlier: the Today page
    treats the last two sessions' trades as today's.
    """
    groups = holdings.get('groups', {})
    if LONG_ACCOUNT not in groups or RESEARCH_ACCOUNT not in groups or not groups[LONG_ACCOUNT].get('positions'):
        raise ValueError('the desk seed is written for the demo portfolio of engine/scripts/create_demo.py')
    day = history_days(today, date.fromisoformat(holdings['date']))
    check_history(today)
    with _portfolio(directory):
        _write_history(Path(directory), day)
        seed_briefs(Path(directory), day[1])
    _settle(Path(directory))


def seed_briefs(directory: Path, day: date) -> None:
    """Store the pre-market (08:45) and post-market (15:45) brief of ``day``, as the routines would make them.

    Built by ``core.routines.premarket`` / ``postmarket`` on the demo's ledger,
    desk and scripted quotes, with the clock set to each brief's due time, so
    every number is what the builders compute from the demo data. The demo does
    not query news (that section says so) and has no model commentary. No
    notification and no run row is written. Must run inside ``_portfolio``.
    """
    import asyncio
    from core import desk_store
    from core.routines import briefs, postmarket, premarket
    ledger = Ledger(directory / 'ledger.sqlite3')
    for module, moment in ((premarket, _at(day, 8, 45)), (postmarket, _at(day, 15, 45))):
        brief, _ = asyncio.run(module.build(day.isoformat(), runtime=_runtime(directory, moment), ledger=ledger,
                                            news_provider='演示模式不联网查询公告与新闻'))
        with desk_store.pinned_now(moment):
            briefs.save(brief)


def _settle(directory: Path) -> None:
    """Leave ``desk.sqlite3`` as a single file, so that reading it creates and changes nothing.

    The store runs in WAL mode, whose readers create (and leave behind) the
    ``-wal`` and ``-shm`` side files. Back in rollback-journal mode a reader
    touches nothing, which is what the read-only demo needs, also on a read-only
    mount. The first write of a normal run switches the store to WAL again.
    """
    import sqlite3
    db = sqlite3.connect(directory / 'desk.sqlite3')
    try:
        mode = db.execute('PRAGMA journal_mode=DELETE').fetchone()[0]
    finally:
        db.close()
    if mode != 'delete':
        raise RuntimeError(f'could not settle desk.sqlite3 (journal mode {mode})')
    # The switch checkpoints and empties the WAL; its index file is a stale leftover.
    for suffix in ('-wal', '-shm'):
        side = directory / ('desk.sqlite3' + suffix)
        if side.exists():
            if side.stat().st_size and suffix == '-wal':
                raise RuntimeError('desk.sqlite3 still has unwritten changes in its WAL')
            side.unlink()


def _runtime(directory, moment: Optional[datetime] = None):
    """The scripted quote source of the demo as a runtime, with its clock set to ``moment``."""
    from core.market.calendar import SessionClock
    from core.market.quotes import QuoteService
    from core.market.runtime import MarketRuntime
    from core.market.sources_fake import FakeQuoteSource
    source = FakeQuoteSource(directory) if moment is None else FakeQuoteSource(directory, now_fn=lambda: moment)
    clock = SessionClock(source.now)
    return MarketRuntime(QuoteService([source], clock, ttl_seconds=0, fx_ttl_seconds=0), clock, 'fake')


def _write_history(directory: Path, day: Mapping[int, date]) -> None:
    from core import desk_store, plans, proposals, watchlist
    from core.alerts import rules

    ledger = Ledger(directory / 'ledger.sqlite3')
    runtime = _runtime(directory)

    def book(moment: datetime, event: dict) -> None:
        """Preview, confirm and link to the plans, as the ledger page does."""
        with desk_store.pinned_now(moment):
            receipt_id = ledger.propose([event])['id']
            ledger.confirm(receipt_id)
            plans.record_links(ledger.proposal(receipt_id), ledger=ledger)

    # D12: a plan for a swing trade that will be closed.
    with desk_store.pinned_now(_at(day[12], 9, 10)):
        swing = plans.create({
            'ticker': 'SHE:DEMOZ', 'account': LONG_ACCOUNT, 'entry_low': '12', 'entry_high': '12.6',
            'stop_price': '11.2', 'target_price': '13.5', 'planned_quantity': '500',
            'thesis': '示例周期股的业绩预告好于预期，博一段波段，到目标价就卖，不做长期持有。',
            'invalidation': '股价跌破 11.2，或者正式业绩低于预告。'})
    with desk_store.pinned_now(_at(day[12], 9, 25)):
        plans.activate(swing['id'])

    # D11: the entry.
    book(_at(day[11], 15, 20), _trade(day[11], 'buy', 'SHE:DEMOZ', '示例周期股', 500, '12.3', 5, 'demoz-buy',
                                      '按计划在入场区间内买入'))

    # D10: the watchlist.
    watched = [('NASDAQ:DEMOW', '示例成长股', '等回调到 45 附近再看，先观察两周。'),
               ('NYSE:DEMOX', '示例价值股', '估值偏低，写了一份草稿计划，等价格进入区间。'),
               ('NASDAQ:DEMOY', '示例新股', '数据源暂时没有它的报价，先记在这里。'),
               ('NYSE:DEMOV', '示例消费股', '和持仓里的示例宽基对照着看。')]
    for minute, (ticker, name, note) in enumerate(watched):
        with desk_store.pinned_now(_at(day[10], 20, minute)):
            watchlist.add(ticker, note, name=name)

    # D9: the plan on a holding; activating it creates its stop-loss and target rules.
    with desk_store.pinned_now(_at(day[9], 9, 10)):
        base = plans.create({
            'ticker': 'SHA:DEMO', 'account': LONG_ACCOUNT, 'entry_low': '58', 'entry_high': '61',
            'stop_price': '54', 'target_price': '66', 'planned_quantity': '1200',
            'review_on': _review_day(day[1]).isoformat(),
            'thesis': '示例宽基回撤企稳后，在 58 到 61 之间把持仓加到 1200 份，长期持有，不追高。',
            'invalidation': '收盘跌破 54 且两周内没有收回，说明这不是短期波动，按计划离场后重新评估。'})
    with desk_store.pinned_now(_at(day[9], 9, 30)):
        plans.activate(base['id'])

    # D8, D7: the add, then the dividend on what is held after it.
    book(_at(day[8], 15, 20), _trade(day[8], 'buy', 'SHA:DEMO', '示例宽基', 200, '58.8', 5, 'demo-buy',
                                     '回撤后按计划加仓'))
    book(_at(day[7], 18, 0), _cash(day[7], 'dividend', LONG_ACCOUNT, 360, 'dividend',
                                   '示例宽基每份分红 0.3 元，共 1200 份', ticker='SHA:DEMO'))

    # D6: rules of the person's own. The weight rule is the one that fires on D3.
    with desk_store.pinned_now(_at(day[6], 9, 20)):
        rules.create({'ticker': 'NASDAQ:DEMO', 'kind': 'day_change_pct', 'threshold': '-4', 'account': RESEARCH_ACCOUNT,
                      'note': '单日大跌时提醒我复查，不自动处理。'}, source='manual')
        weight = rules.create({'ticker': 'SHA:DEMO', 'kind': 'position_weight_max', 'threshold': '50',
                               'account': LONG_ACCOUNT, 'note': '单一持仓不超过组合的一半。'}, source='manual')

    # D5: the exit at the target, and the plan is closed with its reason.
    book(_at(day[5], 14, 40), _trade(day[5], 'sell', 'SHE:DEMOZ', '示例周期股', 500, '13.6', 5, 'demoz-sell',
                                     '到达目标价，全部卖出'))
    with desk_store.pinned_now(_at(day[5], 15, 30)):
        plans.close(swing['id'], '价格到达目标价 13.5，按计划在 13.6 全部卖出，计划完成。')

    # D4: small cash events.
    book(_at(day[4], 15, 10), _cash(day[4], 'fee', LONG_ACCOUNT, 12, 'fee', '虚构的账户服务费'))
    book(_at(day[4], 16, 10), _cash(day[4], 'interest', RESEARCH_ACCOUNT, '8.62', 'interest', '虚构的逆回购利息'))

    # D3: the weight alert, decided by the engine on the scripted prices as of that morning.
    _fire(directory, weight['id'], _at(day[3], 10, 42))

    # D2: a draft plan on a watched ticker. It has no rules until it is activated.
    with desk_store.pinned_now(_at(day[2], 15, 30)):
        plans.create({
            'ticker': 'NYSE:DEMOX', 'entry_low': '30', 'entry_high': '32', 'stop_price': '27.5',
            'target_price': '38', 'planned_weight_pct': '5', 'review_on': _review_day(day[1]).isoformat(),
            'thesis': '示例价值股的估值处于历史低位，等回到 30 到 32 之间再分批买入，先用小仓位试探。',
            'invalidation': '下一季财报收入连续下滑，或者估值修复的逻辑被证伪。'})

    # D1 evening: what the assistant suggests, still waiting. A person confirms it, which the demo refuses.
    # Stamped like the rest of the history, so it is never dated after the day the demo is made for; its
    # expiry follows the real clock (``proposals``), so it is still pending when the demo is opened.
    with desk_store.pinned_now(_at(day[1], 20, 30)):
        proposals.propose(watchlist.PROPOSAL_KIND, {
            'ticker': 'NASDAQ:DEMOQ', 'name': '示例新能源', 'note': '助手建议：和示例成长股对照观察'},
            source='agent:chat', ttl_seconds=proposals.MAX_TTL_SECONDS)


def check_history(today: date) -> None:
    """Refuse a ``today`` whose history cannot be dated: ``ValueError`` with the reason.

    The history reaches ``HISTORY_DAYS`` trading days back and the plans'
    review dates about two weeks past the last of them; near year 1 or year
    9999 those dates do not exist. Writes nothing.
    """
    _review_day(history_days(today)[1], today)


def _review_day(after: date, today: Optional[date] = None) -> date:
    """A mainland trading day about two weeks after ``after``, for the plans' review dates."""
    from core.market.calendar import CN, SessionClock
    clock = SessionClock()
    try:
        day = after + timedelta(days=14)
        while not clock.is_trading_day(CN, day):
            day += timedelta(days=1)
    except OverflowError:
        raise ValueError(f'cannot make the demo for {today or after}: its plans are reviewed about two weeks later, '
                         f'after {date.max}, the last date there is') from None
    return day


def _fire(directory, rule_id: int, moment: datetime) -> bool:
    """Fire ``rule_id`` as the monitor would at ``moment``; refuses when the engine would not fire it.

    One case is not an error: a weight rule the engine holds back because the
    portfolio valuation is unverified at ``moment`` (a year the shipped exchange
    calendars do not cover, where another market's close cannot be confirmed).
    The demo then simply has no fired alert, as the running monitor would have
    none; the return value says whether the alert was recorded.
    """
    from core import desk_store
    from core.alerts import engine, monitor, rules
    from core.ledger import active_ledger
    from core.market.valuation import value_portfolio
    runtime = _runtime(directory, moment)
    item = rules.get(rule_id)
    rule, state = rules.to_rule(item), rules.to_state(item)
    ledger_state = active_ledger(directory).state()
    held = [ticker for account in ledger_state['accounts'].values() for ticker in account['positions']]
    quotes = runtime.quotes.get(list(dict.fromkeys([rule.ticker] + held)))
    valuation = value_portfolio(ledger_state, quotes, runtime.quotes.fx(), None, [])
    weight, reason = engine.weight_for(rule, valuation)
    clock = runtime.clock
    context = engine.Context(now=moment, session_open=clock.is_trading(rule.market), trading_date=clock.local_date(rule.market),
                             weight_pct=weight, weight_reason=reason)
    decision = engine.evaluate(rule, state, quotes[rule.ticker], context)
    if not decision.fired:
        if decision.reason in (engine.WEIGHT_UNAVAILABLE, engine.WEIGHT_ESTIMATED):
            return False
        raise RuntimeError(f'the demo rule {rule_id} would not fire: {decision.reason} ({decision.message})')
    with desk_store.pinned_now(moment), desk_store.transaction() as db:
        rules.save_state(db, rule.id, decision.state)
        monitor.record_fire(db, rule, decision, quotes[rule.ticker], moment)
    return True


def seed_demo(directory, holdings: Mapping, prices: Mapping, rates: Mapping, *,
              previous_prices: Optional[Mapping] = None, ledger: bool = False,
              opened_on: Optional[str] = None, today: Optional[date] = None,
              history: bool = True) -> None:
    """Scripted quotes always; a confirmed ledger and a populated desk only when asked for.

    The default leaves the ledger empty and writes no ``desk.sqlite3``, because
    the opening-balance journey (preview the legacy holdings, then confirm)
    starts from an empty one, and the pages that need a ledger have nothing to
    show without it. ``today`` fixes the day the history is placed relative to.
    ``history=False`` stops after the opening balance: a ledger with nothing
    else in it, for tests and journeys that start from a known minimal state.
    """
    populate = ledger and history
    write_fake_quotes(directory, holdings, prices, rates, previous_prices,
                      extra_quotes=EXTRA_QUOTES if populate else None)
    if ledger:
        seed_ledger(directory, holdings, opened_on or holdings['date'])
    if populate:
        seed_desk(directory, holdings, today)
